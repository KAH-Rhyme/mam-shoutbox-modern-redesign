// Rebuilds the emoji list inside mam-shoutbox-modern-redesign.user.js from the
// emojibase-data package (see package.json for the pinned version).
//
//   npm install
//   npm run build:emoji
//
// Only the block between the BEGIN / END EMOJI DATA markers is replaced. The
// output depends only on the emojibase-data version, so running this twice
// gives an identical file. Nothing in this folder ships with the userscript.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const SCRIPT = join(here, '..', 'mam-shoutbox-modern-redesign.user.js');
const BEGIN = '  // ---- BEGIN EMOJI DATA';
const END = '  // ---- END EMOJI DATA';

const pkg = require('emojibase-data/package.json');
const data = require('emojibase-data/en/data.json');
const messages = require('emojibase-data/en/messages.json');
const github = require('emojibase-data/en/shortcodes/github.json');
const emojibaseLicence = readFileSync(require.resolve('emojibase-data/LICENSE'), 'utf8');
const unicodeLicence = readFileSync(join(here, 'UNICODE-LICENSE-V3.txt'), 'utf8');

const COMPONENT_GROUP = messages.groups.find((group) => group.key === 'component').order;
const FLAGS_GROUP = messages.groups.find((group) => group.key === 'flags').order;
const groupName = new Map(messages.groups.map((group) => [group.order, group.message]));

const words = (text) => text.toLowerCase().split(/[\s_:,]+/).filter(Boolean);
const codePoints = (emoji) => [...emoji.replace(/️/g, '')];

/** The variant for one skin tone (1–5): single-tone, or the same tone throughout. */
function toneVariant(entry, tone) {
  const match = entry.skins.find((skin) =>
    Array.isArray(skin.tone) ? skin.tone.every((t) => t === tone) : skin.tone === tone,
  );
  return match?.emoji;
}

const emoji = data
  .filter((entry) => entry.group !== undefined && entry.group !== COMPONENT_GROUP)
  .sort((a, b) => a.order - b.order);

const lines = [];
let lastGroup = null;
for (const entry of emoji) {
  if (entry.group !== lastGroup) {
    lines.push(JSON.stringify(groupName.get(entry.group)));
    lastGroup = entry.group;
  }
  const labelWords = new Set(words(entry.label));
  const shortcodes = [github[entry.hexcode] ?? []].flat();
  const extra = [...new Set([...(entry.tags ?? []), ...shortcodes].flatMap(words))].filter(
    (word) => !labelWords.has(word),
  );
  const row = [entry.emoji, entry.version, entry.label, extra.join(' ')];
  if (entry.skins?.length) {
    const tones = [1, 2, 3, 4, 5].map((tone) => toneVariant(entry, tone));
    if (tones.every(Boolean)) row.push(tones.join(' '));
  }
  lines.push(JSON.stringify(row));
}

// One single-character emoji per Unicode emoji version, newest first, to test
// which versions this device can draw. Versions made only of sequences (e.g.
// 13.1) are skipped: their parts are older, so the drawing test can't tell.
const tests = new Map();
for (const entry of emoji) {
  if (entry.version <= 1 || entry.group === FLAGS_GROUP || tests.has(entry.version)) continue;
  // type 1 = shown as a colour emoji by default (not as a text symbol).
  if (entry.type === 1 && codePoints(entry.emoji).length === 1) tests.set(entry.version, entry.emoji);
}
const versionTests = [...tests].sort((a, b) => b[0] - a[0]);

const comment = (text) =>
  text
    .trim()
    .split('\n')
    .map((line) => `  //   ${line}`.trimEnd())
    .join('\n');

const block = `${BEGIN} (generated by tools/build-emoji-data.mjs, do not edit by hand) ----
  //
  // Emoji, names and search words from emojibase-data ${pkg.version}
  // (https://emojibase.dev), which uses names and keywords from the Unicode
  // CLDR project (https://cldr.unicode.org). Their notices follow.
  //
${comment(emojibaseLicence)}
  //
${comment(unicodeLicence)}
  //
  // Each emoji line: [emoji, Unicode emoji version, name, more search words,
  // (optional) the five skin-tone variants, light to dark, space-separated].
  // A plain string starts a new section.

  /** [Unicode emoji version, an emoji first added in it], newest first. */
  const EMOJI_VERSION_TESTS = ${JSON.stringify(versionTests)};

  function emojiData() {
    return [
${lines.map((line) => `      ${line},`).join('\n')}
    ];
  }
${END} ----`;

const source = readFileSync(SCRIPT, 'utf8');
const start = source.indexOf(BEGIN);
const endLine = source.indexOf(END);
if (start === -1 || endLine === -1 || endLine < start) {
  throw new Error(`Couldn't find the "${BEGIN.trim()}" / "${END.trim()}" markers in ${SCRIPT}`);
}
const end = source.indexOf('\n', endLine);
const updated = source.slice(0, start) + block + source.slice(end === -1 ? source.length : end);
writeFileSync(SCRIPT, updated);
console.log(`Wrote ${emoji.length} emoji (${versionTests.length} version tests) from emojibase-data ${pkg.version}.`);
